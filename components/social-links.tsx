export function SocialLinks() {
  const autoplayRef = useRef(
    Autoplay({ delay: 2500, stopOnInteraction: false, playOnInit: true })
  );
  const [emblaRef] = useEmblaCarousel(
    {
      loop: true,
      align: "start",
      duration: 40,
      dragFree: true,
    },
    [autoplayRef.current]
  );

  // ponytail: embla loop:true handles infinite scrolling internally
  return (
    <div>
      <div
        className="embla w-full overflow-hidden"
        ref={emblaRef}
        onMouseEnter={() => autoplayRef.current?.stop()}
        onMouseLeave={() => autoplayRef.current?.play()}
        role="region"
        aria-label={i18n.common.socialLinksRegion}
        aria-roledescription="carousel"
      >
        <div className="embla__container flex">
          {socialLinks.map((link, i) => (
            <div
              key={`${link.name}-${i}`}
              className="embla__slide mr-3 shrink-0"
              role="group"
              aria-roledescription="slide"
              aria-label={`Link to ${link.name}`}
              tabIndex={-1}
            >
              <a
                href={link.url}
                target="_blank"
                rel="noopener noreferrer"
                className="bg-secondary border-border/60 group flex h-16 w-24 items-center justify-center rounded-xl border transition-colors hover:bg-black/5 dark:bg-[#1a1a1a] dark:hover:bg-[#252525]"
              >
                <SocialIcon
                  brand={link.brand}
                  className="text-foreground h-6 w-6 opacity-80 transition-opacity group-hover:opacity-100"
                />
              </a>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
