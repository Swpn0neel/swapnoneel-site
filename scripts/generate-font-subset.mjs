// Builds the inlined Inter face used for the site's body text.
//
// Why inline at all: the LCP element on / is a text paragraph. With a normal
// linked webfont (font-display: swap) the paragraph paints once in the
// fallback and then *repaints* when Inter arrives — and that repaint registers
// a second, much later LCP candidate. LCP therefore tracked font arrival time
// and swung between ~1.9s and ~2.8s on Slow 4G. Inlining the face as a data
// URI means it is available when the CSS is parsed, so the text paints in
// Inter the first time and never repaints: LCP collapses onto FCP.
//
// Two reductions keep the inlined payload small enough that the FCP cost is
// worth it (47.3 KiB -> ~20 KiB before base64):
//   1. clamp the variable wght axis to the 400-700 the site actually uses
//   2. subset to latin + the typographic punctuation the prose needs
//
// Not wired into `prebuild` on purpose: this shells out to Python/fonttools,
// which is not guaranteed on the deploy builder. The generated CSS is
// committed instead, and this script is re-run by hand when the font changes.
//   pnpm run generate-font-subset

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const SRC = "assets/fonts/inter-latin-variable.woff2";
const OUT = "app/inter-subset.generated.css";

// Weights declared in the app. Clamping the axis to this range rather than
// shipping the full 100-900 is most of the pre-subset saving.
const WGHT = "400:700";

const UNICODES = [
  "U+0020-007E", // basic latin
  "U+00A0", // nbsp
  "U+00A9", // ©  (footer)
  "U+00B7", // ·
  "U+00C0-00FF", // latin-1 accented letters (names, loanwords in prose)
  "U+0152-0153", // Œ œ
  "U+2013-2014", // – —
  "U+2018-201D", // curly quotes
  "U+2022", // •  (experience titles)
  "U+2026", // …
  "U+2039-203A", // ‹ ›
  "U+20AC", // €
  // Arrows block. → (view-more), ↗ (footer links) and ← (the back link on blog
  // posts and /work/others, 61 occurrences) are all in use; taking the whole
  // range costs a few glyphs and avoids missing one later.
  "U+2190-2199",
].join(",");

// next/font generated this from Inter's own metrics. Kept verbatim so the
// fallback stays metric-matched and CLS stays at 0 if the inline face is ever
// unavailable.
const FALLBACK = `@font-face {
  font-family: "Inter Fallback";
  src: local("Arial");
  ascent-override: 90.44%;
  descent-override: 22.52%;
  line-gap-override: 0%;
  size-adjust: 107.12%;
}`;

function python() {
  for (const [cmd, args] of [
    ["python", []],
    ["python3", []],
    ["py", ["-3"]],
  ]) {
    try {
      execFileSync(cmd, [...args, "-c", "import fontTools"], {
        stdio: "ignore",
      });
      return { cmd, args };
    } catch {
      // try the next candidate
    }
  }
  throw new Error(
    "Need Python with fonttools to regenerate the font subset.\n" +
      "  pip install 'fonttools[woff]'\n" +
      `If you are not changing ${SRC}, you do not need this — ${OUT} is committed.`
  );
}

const py = python();
const run = (...argv) =>
  execFileSync(py.cmd, [...py.args, ...argv], { stdio: "inherit" });

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "inter-subset-"));
const instanced = path.join(tmp, "instanced.woff2");
const subset = path.join(tmp, "subset.woff2");

try {
  run("-m", "fontTools.varLib.instancer", SRC, `wght=${WGHT}`, "-o", instanced);
  run(
    "-m",
    "fontTools.subset",
    instanced,
    `--output-file=${subset}`,
    "--flavor=woff2",
    "--layout-features=kern,liga,calt",
    `--unicodes=${UNICODES}`
  );

  const bytes = fs.readFileSync(subset);
  const css = `/* GENERATED by scripts/generate-font-subset.mjs — do not edit.
   Inter latin, wght ${WGHT}, inlined so the LCP paragraph paints in Inter on
   the first paint instead of repainting when a linked font arrives. */
${FALLBACK}

@font-face {
  font-family: "Inter";
  font-style: normal;
  font-weight: 400 700;
  /* optional is the only value with no bad failure mode here, and it works
     precisely because the face is inlined rather than fetched:
       swap     -> if the face resolves after first paint the text reflows.
                   "Inter Fallback" renders the hero block 27.3px taller than
                   Inter, so that reflow cost a real 0.027 CLS in the field.
       block    -> hides text until the face resolves, risking FCP.
       optional -> never swaps. Resolved in time (the normal case, since there
                   is no network) it paints Inter from the first paint; not
                   resolved, it keeps the fallback for that pageview. Either
                   way the layout is decided once and never shifts. */
  font-display: optional;
  src: url(data:font/woff2;base64,${bytes.toString("base64")}) format("woff2");
}
`;
  fs.writeFileSync(OUT, css);

  const kib = (n) => `${(n / 1024).toFixed(1)} KiB`;
  console.log(
    `${SRC} ${kib(fs.statSync(SRC).size)} -> subset ${kib(bytes.length)} -> ${OUT} ${kib(Buffer.byteLength(css))}`
  );
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
