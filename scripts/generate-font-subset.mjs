// Builds the subsetted Inter face used for the site's body text.
//
// The face used to be emitted as a base64 data URI inside this CSS, so it was
// guaranteed present at first paint. That was paid for on every single request:
// `experimental.inlineCss` re-serialises the whole stylesheet into every HTML
// document *and* into every RSC navigation payload, so the 28 KiB of base64
// rode along each time and was never cacheable. A /contact navigation shipped
// 217 KB, 94% of it duplicated CSS. See next.config.ts for the other half of
// that change.
//
// Linked instead, the face is fetched once and cached for the whole site. It is
// preloaded from the root layout so the request starts at HTML parse rather
// than after the stylesheet resolves, and `font-display: optional` keeps the
// failure mode harmless (see the note on the @font-face below).
//
// Two reductions keep it small (47.3 KiB -> ~21 KiB):
//   1. clamp the variable wght axis to the 400-700 the site actually uses
//   2. subset to latin + the typographic punctuation the prose needs
//
// Not wired into `prebuild` on purpose: this shells out to Python/fonttools,
// which is not guaranteed on the deploy builder. The generated CSS and the
// .woff2 are committed instead, and this script is re-run by hand when the
// font changes.
//   pnpm run generate-font-subset

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const SRC = "assets/fonts/inter-latin-variable.woff2";
const OUT = "app/inter-subset.generated.css";
// Served from /public, so the browser URL is FONT_OUT minus the "public"
// prefix. Kept in sync with the preload in app/layout.tsx. next.config.ts
// serves this immutably and the name carries no content hash, so if the subset
// below changes, rename the file in all three places.
const FONT_OUT = "public/font/inter-latin.woff2";
const FONT_URL = "/font/inter-latin.woff2";

// Weights declared in the app. Clamping the axis to this range rather than
// shipping the full 100-900 is most of the pre-subset saving.
const WGHT = "400:700";

const UNICODES = [
  "U+0020-007E", // basic latin
  "U+00A0", // nbsp
  "U+00A9", // ©  (footer)
  "U+00B7", // ·
  "U+00C0-00FF", // latin-1 accented letters (names, loanwords in prose)
  "U+0152-0153", // Œ œ
  "U+2013-2014", // – —
  "U+2018-201D", // curly quotes
  "U+2022", // •  (experience titles)
  "U+2026", // …
  "U+2039-203A", // ‹ ›
  "U+20AC", // €
  // Arrows block. → (view-more), ↗ (footer links) and ← (the back link on blog
  // posts and /work/others, 61 occurrences) are all in use; taking the whole
  // range costs a few glyphs and avoids missing one later.
  "U+2190-2199",
].join(",");

// next/font generated this from Inter's own metrics. Kept verbatim so the
// fallback stays metric-matched and CLS stays at 0 if the inline face is ever
// unavailable.
const FALLBACK = `@font-face {
  font-family: "Inter Fallback";
  src: local("Arial");
  ascent-override: 90.44%;
  descent-override: 22.52%;
  line-gap-override: 0%;
  size-adjust: 107.12%;
}`;

function python() {
  for (const [cmd, args] of [
    ["python", []],
    ["python3", []],
    ["py", ["-3"]],
  ]) {
    try {
      execFileSync(cmd, [...args, "-c", "import fontTools"], {
        stdio: "ignore",
      });
      return { cmd, args };
    } catch {
      // try the next candidate
    }
  }
  throw new Error(
    "Need Python with fonttools to regenerate the font subset.\n" +
      "  pip install 'fonttools[woff]'\n" +
      `If you are not changing ${SRC}, you do not need this — ${OUT} is committed.`
  );
}

const py = python();
const run = (...argv) =>
  execFileSync(py.cmd, [...py.args, ...argv], { stdio: "inherit" });

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "inter-subset-"));
const instanced = path.join(tmp, "instanced.woff2");
const subset = path.join(tmp, "subset.woff2");

try {
  run("-m", "fontTools.varLib.instancer", SRC, `wght=${WGHT}`, "-o", instanced);
  run(
    "-m",
    "fontTools.subset",
    instanced,
    `--output-file=${subset}`,
    "--flavor=woff2",
    "--layout-features=kern,liga,calt",
    `--unicodes=${UNICODES}`
  );

  const bytes = fs.readFileSync(subset);
  const css = `/* GENERATED by scripts/generate-font-subset.mjs — do not edit.
   Inter latin, wght ${WGHT}. The face itself lives at ${FONT_URL}; it is
   preloaded from app/layout.tsx so the fetch starts at HTML parse. */
${FALLBACK}

@font-face {
  font-family: "Inter";
  font-style: normal;
  font-weight: 400 700;
  /* optional is the only value with no bad failure mode here:
       swap     -> if the face resolves after first paint the text reflows.
                   "Inter Fallback" renders the hero block 27.3px taller than
                   Inter, so that reflow cost a real 0.027 CLS in the field.
       block    -> hides text until the face resolves, risking FCP.
       optional -> never swaps. Resolved in time (the normal case: it is
                   preloaded, cached after the first page, and only 21 KiB) it
                   paints Inter from the first paint; not resolved, it keeps
                   the metric-matched fallback for that pageview. Either way
                   the layout is decided once and never shifts. */
  font-display: optional;
  src: url(${FONT_URL}) format("woff2");
}
`;
  fs.mkdirSync(path.dirname(FONT_OUT), { recursive: true });
  fs.writeFileSync(FONT_OUT, bytes);
  fs.writeFileSync(OUT, css);

  const kib = (n) => `${(n / 1024).toFixed(1)} KiB`;
  console.log(
    `${SRC} ${kib(fs.statSync(SRC).size)} -> ${FONT_OUT} ${kib(bytes.length)}, ${OUT} ${kib(Buffer.byteLength(css))}`
  );
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
