import fs from "fs/promises";
import { createRequire } from "module";
import path from "path";

const require = createRequire(import.meta.url);
const prettier = require("prettier");

const projectsDir = path.join(process.cwd(), "md", "projects");
const outputPath = path.join(
  process.cwd(),
  "lib",
  "project-overlay-content.ts"
);
const checkOnly = process.argv.includes("--check");

async function markdownFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(dir, entry.name);
      if (entry.isDirectory()) return markdownFiles(entryPath);
      return /\.mdx?$/i.test(entry.name) ? [entryPath] : [];
    })
  );
  return nested.flat().sort((a, b) => a.localeCompare(b));
}

// Keep these semantics aligned with the original server extraction and the
// overlay's display cleaning: feature labels lose bold markers, while tech
// labels prefer the first bold span and otherwise stop at an en/em dash.
function parseSection(content, heading) {
  const regex = new RegExp(
    `###\\s+${heading}[\\s\\S]*?\\n([\\s\\S]*?)(?=###|$)`,
    "i"
  );
  const match = content.match(regex);
  if (!match) return [];

  return match[1]
    .split("\n")
    .filter((line) => line.trim().startsWith("-"))
    .map((line) => line.replace(/^-\s*/, "").trim())
    .filter(Boolean);
}

function cleanTechLabel(value) {
  const boldMatch = value.match(/\*\*(.+?)\*\*/);
  return boldMatch ? boldMatch[1] : value.split("—")[0].split("–")[0].trim();
}

const files = await markdownFiles(projectsDir);
const data = {};

for (const file of files) {
  const slug = path.basename(file).replace(/\.mdx?$/i, "");
  if (Object.hasOwn(data, slug)) {
    throw new Error(`Duplicate project slug: ${slug}`);
  }

  const content = await fs.readFile(file, "utf8");
  data[slug] = {
    features: parseSection(content, "Features").map((value) =>
      value.replace(/\*\*/g, "")
    ),
    techStack: parseSection(content, "Tech Stack").map(cleanTechLabel),
  };
}

const unformatted = `// AUTO-GENERATED by scripts/generate-project-overlay-content.mjs.
// Do not edit by hand. Run \`npm run generate-project-overlay-content\`.
import type { ProjectOverlayContent } from "./project-overlay-data";

// Kept in the overlay import graph so card metadata stays small on initial load.
export const projectOverlayContent: Record<string, ProjectOverlayContent> = ${JSON.stringify(data, null, 2)};
`;
const prettierConfig = (await prettier.resolveConfig(outputPath)) ?? {};
if (prettierConfig.plugins) {
  prettierConfig.plugins = prettierConfig.plugins.map((plugin) =>
    typeof plugin === "string" ? require.resolve(plugin) : plugin
  );
}
const generated = await prettier.format(unformatted, {
  ...prettierConfig,
  filepath: outputPath,
});

if (checkOnly) {
  let current = "";
  try {
    current = await fs.readFile(outputPath, "utf8");
  } catch {
    // The comparison below reports the same actionable recovery command for a
    // missing file and a stale one.
  }

  if (current !== generated) {
    console.error(
      "Project overlay content is stale. Run `npm run generate-project-overlay-content`."
    );
    process.exitCode = 1;
  } else {
    console.log(
      `Project overlay content is current (${files.length} projects).`
    );
  }
} else {
  await fs.writeFile(outputPath, generated);
  console.log(`Generated overlay content for ${files.length} projects.`);
}
